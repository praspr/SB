#!/usr/bin/env bash

# Cache helpers for scripts/run_postgres_query.sh.
# Cache files contain DB credentials, so every writer keeps them user-readable only.

postgres_query_cache_repo_root() {
  local script_dir
  script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
  cd "$script_dir/.." && pwd
}

postgres_query_cache_dir() {
  local repo_root
  repo_root="$(postgres_query_cache_repo_root)"
  printf '%s\n' "${POSTGRES_QUERY_CACHE_DIR:-$repo_root/.cache/postgres}"
}

postgres_query_cache_init() {
  local dir
  dir="$(postgres_query_cache_dir)"
  mkdir -p "$dir"
  chmod 700 "$dir"
}

postgres_query_cache_now() {
  date +%s
}

postgres_query_cache_context_key() {
  printf '%s' "$1" | tr -c '[:alnum:]_.-' '_'
}

postgres_query_cache_context_file() {
  local context_key
  context_key="$(postgres_query_cache_context_key "$1")"
  printf '%s/%s.env\n' "$(postgres_query_cache_dir)" "$context_key"
}

postgres_query_cache_clear_context() {
  local cache_file
  cache_file="$(postgres_query_cache_context_file "$1")"
  rm -f "$cache_file"
}

postgres_query_cache_clear_all() {
  local dir
  dir="$(postgres_query_cache_dir)"
  rm -rf "$dir"
}

postgres_query_cache_load_context() {
  local context="$1"
  local cache_file
  cache_file="$(postgres_query_cache_context_file "$context")"

  if [[ "${POSTGRES_QUERY_CACHE_CLEAR:-0}" == "1" ]]; then
    postgres_query_cache_clear_context "$context"
    return 1
  fi

  [[ -f "$cache_file" ]] || return 1

  # shellcheck disable=SC1090
  source "$cache_file"
}

postgres_query_cache_write_context() {
  local context="$1"
  local cache_file
  cache_file="$(postgres_query_cache_context_file "$context")"
  postgres_query_cache_init

  local cached_at
  cached_at="$(postgres_query_cache_now)"

  umask 077
  POSTGRES_QUERY_CACHE_CONTEXT="$context" \
  POSTGRES_QUERY_CACHE_FILE="$cache_file" \
  POSTGRES_QUERY_CACHE_CACHED_AT="$cached_at" \
  KUBE_CONTEXT="${KUBE_CONTEXT:-}" \
  POSTGRES_POD="${POSTGRES_POD:-}" \
  KUBE_NAMESPACE="${KUBE_NAMESPACE:-}" \
  SECRET_NAMESPACE="${SECRET_NAMESPACE:-}" \
  SECRET_NAME="${SECRET_NAME:-}" \
  DB_HOST="${DB_HOST:-}" \
  DB_PORT="${DB_PORT:-}" \
  DB_NAME="${DB_NAME:-}" \
  DB_USER="${DB_USER:-}" \
  DB_PASSWORD="${DB_PASSWORD:-}" \
  python3 <<'PY'
import os
import shlex

cache_file = os.environ["POSTGRES_QUERY_CACHE_FILE"]
keys = [
    "KUBE_CONTEXT",
    "POSTGRES_POD",
    "KUBE_NAMESPACE",
    "SECRET_NAMESPACE",
    "SECRET_NAME",
    "DB_HOST",
    "DB_PORT",
    "DB_NAME",
    "DB_USER",
    "DB_PASSWORD",
]

with open(cache_file, "w", encoding="utf-8") as f:
    f.write("# Generated by scripts/run_postgres_query.sh. Contains DB credentials.\n")
    f.write(f"cached_at={shlex.quote(os.environ['POSTGRES_QUERY_CACHE_CACHED_AT'])}\n")
    for key in keys:
        f.write(f"{key}={shlex.quote(os.environ.get(key, ''))}\n")
PY
  chmod 600 "$cache_file"
}
